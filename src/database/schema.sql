-- Fetches all public recipes and includes interaction data for the requesting user.
-- Must be run with SECURITY DEFINER to access the auth.users table for owner details.
CREATE OR REPLACE FUNCTION get_public_recipes_with_interactions(request_user_id uuid)
RETURNS TABLE(
    id uuid,
    title text,
    featured_image_url text,
    category text,
    created_at timestamp with time zone,
    user_id uuid,
    is_public boolean,
    like_count bigint,
    comment_count bigint,
    has_liked boolean,
    owner_full_name text,
    owner_avatar_url text
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    r.id, r.title, r.featured_image_url, r.category, r.created_at, r.user_id, r.is_public,
    (SELECT COUNT(*) FROM likes WHERE recipe_id = r.id) AS like_count,
    (SELECT COUNT(*) FROM comments WHERE recipe_id = r.id) AS comment_count,
    (CASE WHEN request_user_id IS NOT NULL THEN
      EXISTS(SELECT 1 FROM likes li WHERE li.recipe_id = r.id AND li.user_id = request_user_id)
    ELSE
      false
    END) AS has_liked,
    u.raw_user_meta_data->>'full_name' AS owner_full_name,
    u.raw_user_meta_data->>'avatar_url' AS owner_avatar_url
  FROM my_recipies AS r
  JOIN auth.users AS u ON r.user_id = u.id
  WHERE r.is_public = true;
END;
$$;


-- Fetches recipes for a specific user and includes interaction data for the requesting user.
-- Must be run with SECURITY DEFINER to access the auth.users table for owner details.
