-- Stores user-created recipes
CREATE TABLE public.my_recipies (
    id uuid NOT NULL DEFAULT uuid_generate_v4 (),
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    user_id uuid NOT NULL DEFAULT auth.uid(),
    title text NOT NULL,
    details text,
    ingredients text[],
    time_to_cook text,
    featured_image_url text,
    result_image_urls text[],
    tags text[],
    category text,
    is_public boolean NOT NULL DEFAULT false,
    nutrition jsonb,
    CONSTRAINT my_recipies_pkey PRIMARY KEY (id),
    CONSTRAINT my_recipies_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users (id) ON UPDATE CASCADE ON DELETE CASCADE
);
-- RLS Policy: Users can only manage their own recipes.
ALTER TABLE public.my_recipies ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view public recipes" ON public.my_recipies FOR SELECT USING (is_public = true);
CREATE POLICY "Users can manage their own recipes" ON public.my_recipies FOR ALL USING (auth.uid() = user_id);


-- Stores likes for recipes
CREATE TABLE public.likes (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    user_id uuid NOT NULL DEFAULT auth.uid(),
    recipe_id uuid NOT NULL,
    CONSTRAINT likes_pkey PRIMARY KEY (id),
    CONSTRAINT likes_recipe_id_fkey FOREIGN KEY (recipe_id) REFERENCES public.my_recipies (id) ON DELETE CASCADE,
    CONSTRAINT likes_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users (id) ON DELETE CASCADE,
    CONSTRAINT likes_user_id_recipe_id_key UNIQUE (user_id, recipe_id)
);
-- RLS Policy: Users can only manage their own likes.
ALTER TABLE public.likes ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view all likes" ON public.likes FOR SELECT USING (true);
CREATE POLICY "Users can manage their own likes" ON public.likes FOR ALL USING (auth.uid() = user_id);


-- Stores comments for recipes
CREATE TABLE public.comments (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    user_id uuid NOT NULL DEFAULT auth.uid(),
    recipe_id uuid NOT NULL,
    content text,
    user_full_name text,
    user_avatar_url text,
    CONSTRAINT comments_pkey PRIMARY KEY (id),
    CONSTRAINT comments_recipe_id_fkey FOREIGN KEY (recipe_id) REFERENCES public.my_recipies (id) ON DELETE CASCADE,
    CONSTRAINT comments_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users (id) ON DELETE CASCADE
);
-- RLS Policy: Users can only manage their own comments.
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view all comments" ON public.comments FOR SELECT USING (true);
CREATE POLICY "Users can manage their own comments" ON public.comments FOR ALL USING (auth.uid() = user_id);


-- Stores user search history
CREATE TABLE public.history (
