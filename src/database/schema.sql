    is_public boolean,
    like_count bigint,
    comment_count bigint,
    has_liked boolean,
    owner_full_name text,
    owner_avatar_url text
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN QUERY
  SELECT
    r.id, r.title, r.featured_image_url, r.category, r.created_at, r.user_id, r.is_public,
    (SELECT COUNT(*) FROM likes WHERE recipe_id = r.id) AS like_count,
    (SELECT COUNT(*) FROM comments WHERE recipe_id = r.id) AS comment_count,
