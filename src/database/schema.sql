-- Finds public recipes that contain a given set of ingredients.
-- This function does not need SECURITY DEFINER as it does not access auth.users directly.
CREATE OR REPLACE FUNCTION find_recipes_by_ingredients(p_ingredients text[], p_request_user_id uuid)
RETURNS TABLE (
    id uuid,
    title text,
    featured_image_url text,
    category text,
    created_at text,
    user_id uuid,
    is_public boolean,
    like_count integer,
    comment_count integer,
    has_liked boolean,
    ingredients text[]
) 
AS $$
BEGIN
    RETURN QUERY
    SELECT
        r.id,
        r.title,
        r.featured_image_url,
        r.category,
        r.created_at::text,
        r.user_id,
        r.is_public,
        (SELECT count(*)::integer FROM likes l WHERE l.recipe_id = r.id) as like_count,
        (SELECT count(*)::integer FROM comments c WHERE c.recipe_id = r.id) as comment_count,
        EXISTS(SELECT 1 FROM likes li WHERE li.recipe_id = r.id AND li.user_id = p_request_user_id) AS has_liked,
        r.ingredients
    FROM
        my_recipies r
    WHERE
        r.is_public = true AND r.ingredients @> p_ingredients;
END;
$$ LANGUAGE plpgsql;
